-- Opsional: skema ini dibuat otomatis oleh SchemaInitializer saat aplikasi pertama kali jalan.
-- File ini disediakan untuk membuat tabel secara manual (mis. lewat pgAdmin/psql).
-- Perintah psql:
--   psql -U postgres -h localhost -p 5432 -d pbo2026_cashflow -f database/02-schema.sql

CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(200) NOT NULL,
    role VARCHAR(20) NOT NULL,
    photo_path VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS transactions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    description TEXT NOT NULL,
    amount BIGINT NOT NULL,
    type VARCHAR(20) NOT NULL,
    proof_path VARCHAR(500),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_transactions_user FOREIGN KEY (user_id) REFERENCES users(id)
);
